"""Derive the plane-strain Kirsch solution (circular hole of radius a, axis z,
remote uniaxial stress S along x, infinite medium) and write it as C++ to
src/kirsch_exact_gen.hpp.

With u_z = 0 and sigma_zz = nu (sigma_xx + sigma_yy) this is an exact 3D
elasticity solution, so prescribing its traction on every face of a plate of
any thickness gives an exact test with SCF sigma_xx(0, a) / S = 3.

The script checks that the displacement below (plane strain, kappa = 3 - 4 nu)
reproduces the Kirsch stresses, that Navier's equation holds and that the hole
is traction-free.

usage: python3 python/gen_kirsch_exact.py  (needs sympy)
"""

import os

import sympy as sp

x, y, z = sp.symbols("x y z", real=True)
a, S, mu, nu = sp.symbols("a S mu nu", positive=True)
r, th = sp.symbols("r theta", positive=True)
lam = 2 * mu * nu / (1 - 2 * nu)
kap = 3 - 4 * nu

# Plane-strain Kirsch displacement in polar form.
ur = S * a / (8 * mu) * ((r / a) * (kap - 1) + 2 * a / r
                         + (2 * r / a + 2 * (1 + kap) * a / r - 2 * a**3 / r**3) * sp.cos(2 * th))
ut = -S * a / (8 * mu) * (2 * r / a + 2 * (kap - 1) * a / r + 2 * a**3 / r**3) * sp.sin(2 * th)

# Kirsch stresses (Timoshenko & Goodier, Sec. 35).
srr = S / 2 * (1 - a**2 / r**2) + S / 2 * (1 - 4 * a**2 / r**2 + 3 * a**4 / r**4) * sp.cos(2 * th)
stt = S / 2 * (1 + a**2 / r**2) - S / 2 * (1 + 3 * a**4 / r**4) * sp.cos(2 * th)
srt = -S / 2 * (1 + 2 * a**2 / r**2 - 3 * a**4 / r**4) * sp.sin(2 * th)

# Strains in polar coordinates and plane-strain Hooke's law.
err = sp.diff(ur, r)
ett = ur / r + sp.diff(ut, th) / r
ert = (sp.diff(ur, th) / r + sp.diff(ut, r) - ut / r) / 2
tr = err + ett
for got, want in [(lam * tr + 2 * mu * err, srr), (lam * tr + 2 * mu * ett, stt), (2 * mu * ert, srt)]:
    assert sp.simplify(got - want) == 0
assert sp.simplify(srr.subs(r, a)) == 0 and sp.simplify(srt.subs(r, a)) == 0
print("Kirsch stresses reproduced; hole traction-free; SCF =",
      sp.simplify(stt.subs({r: a, th: sp.pi / 2}) / S))

# Cartesian displacement and gradient.
c, s = x / sp.sqrt(x**2 + y**2), y / sp.sqrt(x**2 + y**2)
pol = {r: sp.sqrt(x**2 + y**2)}
cos2, sin2 = c**2 - s**2, 2 * s * c
urc = ur.subs(sp.cos(2 * th), sp.Symbol("C2")).subs(sp.sin(2 * th), sp.Symbol("S2"))
utc = ut.subs(sp.cos(2 * th), sp.Symbol("C2")).subs(sp.sin(2 * th), sp.Symbol("S2"))
rep = {sp.Symbol("C2"): cos2, sp.Symbol("S2"): sin2}
urx, utx = urc.subs(rep).subs(pol), utc.subs(rep).subs(pol)
U = sp.Matrix([urx * c - utx * s, urx * s + utx * c, 0])
X = sp.Matrix([x, y, z])
G = U.jacobian(X)
eps = (G + G.T) / 2
sig = lam * eps.trace() * sp.eye(3) + 2 * mu * eps
nav = [sp.simplify(sum(sp.diff(sig[i, j], v) for j, v in enumerate((x, y, z)))) for i in range(3)]
assert all(e == 0 for e in nav), nav
assert sp.simplify(sig[0, 0].subs({x: 0, y: a}) / S - 3) == 0
print("Navier's equation holds; sigma_xx(0, a) = 3 S")

exprs = list(U) + [G[i, j] for i in range(3) for j in range(3)]
reps, red = sp.cse(exprs)
body = ["  const double %s = %s;" % (sym, sp.ccode(e)) for sym, e in reps]
body += ["  u(%d) = %s;" % (i, sp.ccode(red[i])) for i in range(3)]
body += ["  G(%d, %d) = %s;" % (k // 3, k % 3, sp.ccode(red[3 + k])) for k in range(9)]

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "kirsch_exact_gen.hpp")
with open(out, "w") as f:
    f.write("// Generated by python/gen_kirsch_exact.py. Do not edit.\n")
    f.write("// Plane-strain Kirsch field: circular hole of radius a on the z axis, infinite\n")
    f.write("// medium, remote uniaxial stress S along x: displacement u and gradient\n")
    f.write("// G_ij = du_i/dx_j. SCF sigma_xx(0, a, z) / S = 3.\n")
    f.write("#pragma once\n\n#include <Eigen/Dense>\n#include <cmath>\n\nnamespace igabem {\n\n")
    f.write("inline void kirschField(double x, double y, double z, double a, double S, double mu,\n")
    f.write("                        double nu, Eigen::Vector3d& u, Eigen::Matrix3d& G) {\n")
    f.write("  (void)z;\n")
    f.write("\n".join(body))
    f.write("\n}\n\n}  // namespace igabem\n")
print("wrote", os.path.normpath(out))
