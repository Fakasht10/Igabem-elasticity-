"""Derive the exact solution for a spherical cavity in an infinite elastic
medium under remote uniaxial tension S along z (Goodier 1933; Southwell &
Gough 1926) and write it as C++ to src/cavity_exact_gen.hpp.

The perturbation of the remote field is a combination of three decaying
Papkovich-Neuber solutions (all satisfy Navier's equation identically):

  u1 = x / r^3                                   (centre of dilatation)
  u2 = grad d^2(1/r)/dz^2                        (harmonic potential)
  u3 = 4(1-nu) e_z d(1/r)/dz - grad(z d(1/r)/dz)   (Papkovich vector B = e_z d(1/r)/dz)

and the three constants follow from sigma n = 0 on r = a. The script checks
Navier's equation and the traction-free condition symbolically and prints the
stress concentration factor sigma_zz(a, 0, 0) / S = (27 - 15 nu) / (2 (7 - 5 nu)).

usage: python3 python/gen_cavity_exact.py  (needs sympy)
"""

import os

import sympy as sp

x, y, z = sp.symbols("x y z", real=True)
a, S, mu, nu = sp.symbols("a S mu nu", positive=True)
A, B, C = sp.symbols("A B C")
X = sp.Matrix([x, y, z])
r = sp.sqrt(x**2 + y**2 + z**2)
lam = 2 * mu * nu / (1 - 2 * nu)
E = 2 * mu * (1 + nu)


def grad(f):
    return sp.Matrix([sp.diff(f, v) for v in (x, y, z)])


phi = 1 / r
u1 = X / r**3
u2 = grad(sp.diff(phi, z, 2))
u3 = 4 * (1 - nu) * sp.Matrix([0, 0, sp.diff(phi, z)]) - grad(z * sp.diff(phi, z))
uinf = S / E * sp.Matrix([-nu * x, -nu * y, z])


def stress(u):
    G = u.jacobian(X)
    eps = (G + G.T) / 2
    return lam * eps.trace() * sp.eye(3) + 2 * mu * eps


u = uinf + A * u1 + B * u2 + C * u3
sig = stress(u)
t = sig * X / r

# Traction-free cavity: rational points on the sphere give exact linear equations.
pts = [(sp.Rational(3, 5), sp.Rational(4, 5)), (sp.Rational(5, 13), sp.Rational(12, 13)),
       (sp.Rational(8, 17), sp.Rational(15, 17)), (sp.Rational(4, 5), sp.Rational(3, 5))]
eqs = [sp.together(t[i].subs({x: a * s, y: 0, z: a * c})) for s, c in pts for i in (0, 2)]
sol = {k: sp.factor(v) for k, v in sp.solve(eqs, [A, B, C], dict=True)[0].items()}
print("constants:", sol)

ue = u.subs(sol)
se = stress(ue)
nav = [sp.simplify(sum(sp.diff(se[i, j], v) for j, v in enumerate((x, y, z)))) for i in range(3)]
assert all(e == 0 for e in nav), nav
for p in [(sp.Rational(1, 3), sp.Rational(2, 3), sp.Rational(2, 3)),
          (sp.Rational(2, 7), sp.Rational(3, 7), sp.Rational(6, 7))]:
    sub = {x: a * p[0], y: a * p[1], z: a * p[2]}
    res = [sp.simplify((se * X / r)[i].subs(sub)) for i in range(3)]
    assert all(e == 0 for e in res), res
scf = sp.factor(sp.simplify(se[2, 2].subs({x: a, y: 0, z: 0}) / S))
print("SCF:", scf, "=", scf.subs(nu, sp.Rational(1, 4)), "at nu = 1/4")

G = ue.jacobian(X)
exprs = list(ue) + [G[i, j] for i in range(3) for j in range(3)]
reps, red = sp.cse(exprs)
body = []
for s, e in reps:
    body.append("  const double %s = %s;" % (s, sp.ccode(e)))
for i in range(3):
    body.append("  u(%d) = %s;" % (i, sp.ccode(red[i])))
for k in range(9):
    body.append("  G(%d, %d) = %s;" % (k // 3, k % 3, sp.ccode(red[3 + k])))

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "cavity_exact_gen.hpp")
with open(out, "w") as f:
    f.write("// Generated by python/gen_cavity_exact.py. Do not edit.\n")
    f.write("// Spherical cavity of radius a at the origin, infinite medium, remote\n")
    f.write("// uniaxial stress S along z: displacement u and gradient G_ij = du_i/dx_j.\n")
    f.write("// SCF sigma_zz(a,0,0)/S = %s.\n" % sp.ccode(scf))
    f.write("#pragma once\n\n#include <Eigen/Dense>\n#include <cmath>\n\nnamespace igabem {\n\n")
    f.write("inline void goodierField(double x, double y, double z, double a, double S, double mu,\n")
    f.write("                         double nu, Eigen::Vector3d& u, Eigen::Matrix3d& G) {\n")
    f.write("\n".join(body))
    f.write("\n}\n\n}  // namespace igabem\n")
print("wrote", os.path.normpath(out))
