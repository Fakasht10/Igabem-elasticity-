"""Derive the Boussinesq point-load field of an elastic half-space and write it as C++ to
src/boussinesq_exact_gen.hpp.

Half-space z < 0 (surface z = 0, depth zeta = -z), unit force at the origin pushing into
the solid (direction -e_z). Johnson, Contact Mechanics (1985), eq. 3.20, with
rho = sqrt(x^2 + y^2 + zeta^2):

  u_x    = 1/(4 pi G) [ x zeta / rho^3 - (1 - 2 nu) x / (rho (rho + zeta)) ]
  u_y    = same with y
  u_zeta = 1/(4 pi G) [ zeta^2 / rho^3 + 2 (1 - nu) / rho ],   u_z = -u_zeta

The script checks Navier's equation, that the surface z = 0 is traction-free away from
the origin, and that sigma_zz integrates to -1 over a plane z = -c (the load is carried).
src/problems/half_space.hpp integrates the field over a uniformly pressed disk, which is
exact half-space data for the partially loaded block (app/bc_validate halfspace).

usage: python3 python/gen_boussinesq_exact.py  (needs sympy)
"""

import os

import sympy as sp

x, y, z = sp.symbols("x y z", real=True)
G, nu = sp.symbols("G nu", positive=True)
zeta = -z
rho = sp.sqrt(x**2 + y**2 + zeta**2)
c = 1 / (4 * sp.pi * G)
ux = c * (x * zeta / rho**3 - (1 - 2 * nu) * x / (rho * (rho + zeta)))
uy = c * (y * zeta / rho**3 - (1 - 2 * nu) * y / (rho * (rho + zeta)))
uz = -c * (zeta**2 / rho**3 + 2 * (1 - nu) / rho)
U = sp.Matrix([ux, uy, uz])
X = sp.Matrix([x, y, z])
Gr = U.jacobian(X)
lam = 2 * G * nu / (1 - 2 * nu)
eps = (Gr + Gr.T) / 2
sig = lam * eps.trace() * sp.eye(3) + 2 * G * eps

# Navier (spot checks at rational points: the symbolic simplification is slow)
pts = [(sp.Rational(1, 3), sp.Rational(2, 5), -sp.Rational(3, 7)), (sp.Rational(-2, 3), sp.Rational(1, 5), -2)]
for P in pts:
    sub = dict(zip((x, y, z), P))
    for i in range(3):
        div = sum(sp.diff(sig[i, j], v) for j, v in enumerate((x, y, z)))
        val = sp.N(div.subs(sub).subs({G: 1, nu: sp.Rational(1, 4)}), 30)
        assert abs(val) < 1e-25, val
# surface traction sigma . e_z at z = 0, r > 0
for i in range(3):
    val = sp.N(sig[i, 2].subs({z: 0, x: sp.Rational(3, 7), y: sp.Rational(1, 3)}).subs({G: 1, nu: sp.Rational(1, 4)}), 30)
    assert abs(val) < 1e-25, val
print("Navier's equation holds; surface traction-free away from the load")

# carried load: int sigma_zz over the plane z = -1 (polar, numeric)
import mpmath as mp  # noqa: E402

szz = sp.lambdify((x, y, z), sig[2, 2].subs({G: 1, nu: sp.Rational(1, 4)}), "mpmath")
tot = mp.quad(lambda r: 2 * mp.pi * r * szz(r, 0, -1), [0, 1, 10, mp.inf])
assert abs(tot + 1) < 1e-10, tot
print("int sigma_zz over z = -1: %.12f (load -1 carried)" % float(tot))

exprs = list(U) + [Gr[i, j] for i in range(3) for j in range(3)]
reps, red = sp.cse(exprs)
body = ["  const double %s = %s;" % (sym, sp.ccode(e)) for sym, e in reps]
body += ["  u(%d) = %s;" % (i, sp.ccode(red[i])) for i in range(3)]
body += ["  Gr(%d, %d) = %s;" % (k // 3, k % 3, sp.ccode(red[3 + k])) for k in range(9)]

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "boussinesq_exact_gen.hpp")
with open(out, "w") as f:
    f.write("// Generated by python/gen_boussinesq_exact.py. Do not edit.\n")
    f.write("// Boussinesq field of the half-space z < 0: unit force at the origin pushing into the\n")
    f.write("// solid (-e_z); displacement u and gradient Gr_ij = du_i/dx_j, shear modulus G.\n")
    f.write("#pragma once\n\n#include <Eigen/Dense>\n#include <cmath>\n\nnamespace igabem {\n\n")
    f.write("inline void boussinesqField(double x, double y, double z, double G, double nu, Eigen::Vector3d& u,\n")
    f.write("                            Eigen::Matrix3d& Gr) {\n")
    f.write("\n".join(body))
    f.write("\n}\n\n}  // namespace igabem\n")
print("wrote", os.path.normpath(out))
